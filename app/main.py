def cash_with_loan_chart(check: dict, height: int = 230) -> go.Figure:
    """The borrower's typical bank balance with and without the loan (both from the same simulations)."""
    x = pd.to_datetime(check["dates"])
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=x, y=np.asarray(check["p50_without"]) / 1e5, mode="lines", name="Without the loan",
                             line=dict(width=2, color="#94A3B8", dash="dot"),
                             hovertemplate="Without: ₹%{y:.2f} L<extra></extra>"))
    fig.add_trace(go.Scatter(x=x, y=np.asarray(check["p50_with"]) / 1e5, mode="lines", name="With the loan",
                             line=dict(width=3, color="#00E5FF"), hovertemplate="With: ₹%{y:.2f} L<extra></extra>"))
    fig.add_hline(y=0, line_dash="dash", line_color="#EF4444", line_width=1.2)
    fig.update_layout(
        paper_bgcolor="#111827", plot_bgcolor="#111827", height=height, margin=dict(l=40, r=10, t=10, b=30),
        font=dict(color="#CBD5E1", size=11), hovermode="x unified",
        legend=dict(orientation="h", y=1.12, x=0, bgcolor="rgba(0,0,0,0)"),
        xaxis=dict(gridcolor="#1F2937", tickformat="%b %d"),
        yaxis=dict(gridcolor="#1F2937", tickprefix="₹", ticksuffix=" L"),
        hoverlabel=dict(bgcolor="#0F172A", font=dict(color="#F8FAFC")),
    )
    return fig


