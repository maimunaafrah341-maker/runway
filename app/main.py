def loan_calendar(rows: list, title: str) -> None:
    """A dated to-do table for the agreed loans, plus the same dates as a calendar file with reminders."""
    rows = sorted(rows, key=lambda x: pd.Timestamp(x[0]))
    # A plain table (not a grid) so every row and every note shows in full, without scrolling.
    lines = ["| Date | What to do | Amount | Note |", "|:--|:--|--:|:--|"]
    for d, what, amt, note in rows:
        nb = " "                              # keep dates and amounts on one line
        money = "" if amt is None else (f":green[{inr(amt, signed=True)}]" if amt > 0 else inr(amt))
        date_txt = f"{pd.Timestamp(d):%a, %b %d}".replace(" ", nb)
        money = money.replace(" ", nb).replace("+₹", "+⁠₹").replace("−₹", "−⁠₹")   # no break after a sign
        lines.append(f"| {date_txt} | **{what}** | {money} | {note} |")
    st.markdown("\n".join(lines))
    events = [(d, what, f"{what}{'' if amt is None else f' ({inr(amt, signed=True)})'}. {note}")
              for d, what, amt, note in rows]
    st.download_button("Add these dates to my calendar", calendar_ics(events, f"Runway: {title}").encode("utf-8"),
                       file_name="runway_loan_dates.ics", mime="text/calendar", icon=":material/event:",
                       type="primary", on_click="ignore", key=f"ics_{BIZ_KEY}",
                       help="A calendar file (.ics) for Google Calendar, Outlook or your phone, with a reminder "
                            "the day before each date.")


